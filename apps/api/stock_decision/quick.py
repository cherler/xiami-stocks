"""三十秒写下一个判断。

## 为什么要单独做这件事

第一性原理推下来的结论：这个系统一年的总产出，是大约 10 个决定。其余全是输入。
而**输入端我们做了十几个功能，输出端一个都没真正跑起来过**。

再往下追一层：为什么没跑起来？因为写下一个判断的成本太高——
先建公司档案、等同步、走到那家公司的某个页签、填一堆字段。
十分钟起步的事，一闪而过的念头撑不到那里。

一个判断记录的**不可再分内核只有三句话**：

    我看的是哪家 · 为什么 · 什么情况下我认错

其余全部可以事后补或者推导。

## 认错条件为什么不能省

省掉它，剩下的就是一句无法被推翻的感想。而这个产品的全部价值就建立在
「写下来的东西能被事实检验」上：没有认错条件，反证命中永远不会触发，
复核无从谈起，季度归因也没有对照。**那不是少填一栏，是这条记录作废。**

## 但它是最难写的一栏，所以由代码把候选备好

难在要凭空想出一个**具体到能被判定**的条件。「基本面恶化」不算——
什么叫恶化？

所以这里从这家公司**自己的历史**里算出几条候选，每条都带真实数字：

- 营收连续两季同比下滑（它近五年出现过几次，写在旁边）
- 净利率跌破 X%（X = 它近五年的最低值）
- 市盈率超过 X 倍（X = 它自己近五年 PE 的 P75）

**候选不是推荐。** 它们的作用是让人看见「一个可判定的条件长什么样」，
然后改成自己的。所以每条都写明这个数字是从哪来的——
一个不知道出处的门槛，跟「基本面恶化」一样没用。
"""

from __future__ import annotations

from typing import Any

# 至少要几期年报才敢从历史里给门槛。样本太少时给出来的数字看着精确，其实是噪音。
MIN_YEARS = 3


def _fmt(value: float) -> str:
    return f"{value:g}"


def counter_suggestions(history: dict[str, Any], band: dict[str, Any],
                        current_pe: float | None = None) -> list[dict[str, Any]]:
    """从这家公司自己的数据里，算出几条**可判定**的认错条件。

    每条都带出处。**一个不知道数字从哪来的门槛，跟「基本面恶化」一样没用**——
    到了要判定的那天，你会开始跟自己讨价还价。
    """
    out: list[dict[str, Any]] = []
    years = history.get("years") or []

    # 一、增长停下来。用「连续两期年报营收同比下滑」而不是单期——
    # 单期下滑太常见（这家公司近五年里就有），会让这条条件天天在响。
    growth = history.get("yearly_growth") or []
    if len(years) >= MIN_YEARS:
        negatives = sum(1 for g in growth if g < 0)
        out.append({
            "text": "连续两个年度营收同比下滑",
            "why": (f"它最近 {len(growth)} 个年度里有 {negatives} 年是负增长"
                    + ("——单期下滑对它并不罕见，所以要求连续两期" if negatives else
                       "——一次都没出现过，所以这条一旦触发就是真的变了")),
        })

    # 二、赚钱的能力破位。门槛取它自己的历史最低，不取一个整数——
    # 整数门槛（比如「净利率跌破 40%」）是我在编，历史最低是它自己的事实。
    low = history.get("margin_low")
    # **样本量要用统计窗口的，不是完整序列的。** margin_low 只统计最近几期
    # （见 scenarios.RECENT_YEARS），而 years 是完整序列——茅台有 28 期，
    # 写成「近 28 期的最低值」就是在说谎，而那句话恰恰是让人相信这个门槛的理由。
    window_covered = history.get("window_covered") or len(years)
    if low is not None and len(years) >= MIN_YEARS:
        out.append({
            "text": f"年报净利率跌破 {_fmt(low)}%",
            "why": f"这是它近 {window_covered} 期年报里的最低值——跌破就意味着比它自己最差的时候还差",
        })

    # 三、价格贵到没有安全边际。同样用它自己的分位，不用一个通用的 PE 上限：
    # 30 倍对白酒和对银行完全是两件事。
    p75 = band.get("p75")
    if p75:
        out.append({
            "text": f"市盈率涨到 {_fmt(round(float(p75), 1))} 倍以上",
            "why": (f"这是它自己近五年 PE 的 75 分位"
                    + (f"（当前 {_fmt(round(float(current_pe), 1))} 倍）" if current_pe else "")
                    + "——用它自己的分位，而不是一个通用的倍数上限"),
        })

    # 四、留一条给"我说不清但我知道会变"的情况。**必须有一条空的**：
    # 全是算出来的候选会让人以为认错条件只能是财务指标，
    # 而最要命的那些（管理层换人、主业转向、监管变天）恰恰算不出来。
    out.append({
        "text": "",
        "why": "自己写一条。最要命的那几种（管理层换人、主业转向、监管变天）算不出来，"
               "只能你自己想——但仍然要写成一句**能判定真假**的话。",
    })
    return out


def validate(claim: str, counter: str) -> str:
    """写下之前的最后一道关。返回空串表示可以存。

    只拦两件事：太短的主张，和空的认错条件。**不做措辞审查**——
    这里是自己的记录本，不是作文课。
    """
    if len(claim.strip()) < 3:
        return "先用一句话说清你的判断"
    if not counter.strip():
        return ("认错条件不能空。**没有它，这条记录就是一句无法被推翻的感想**——"
                "反证命中永远不会触发，复核也无从谈起。下面有几条从这家公司自己的"
                "历史里算出来的候选，挑一条改成你的就行。")
    return ""
