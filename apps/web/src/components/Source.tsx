/**
 * 出处记号：挂在数字后面的那个小标记。
 *
 * ## 这是整套设计的签名
 *
 * 这个产品跟所有炒股软件的区别只有一条：**每个数都能点回原文核对**。
 * 而现在它把这件事藏起来——产业链位置的年报原文折在 `<details>` 里，
 * 头顶压着三行解释。**解释在最显眼处，证据在折叠里，正好反了。**
 *
 * 所以：凡是显示数字的地方，出处跟数字在同一个视觉单元里。
 *
 *     88.66% ▸年报        点开：原文那一段 + 打开年报
 *     15 亿  ▸公告
 *     19.79  ▸底座
 *     —      ▸模型推断    ← 不可核对的，明确标出来
 *
 * ## 四种来源分开，因为它们的可信度不一样
 *
 * 「年报原文」和「模型推断」在页面上必须一眼分得开——**那正是这个产品
 * 最该守住的区别**，而现在它只靠一段文字说明（「关系来自模型的世界知识，
 * 可能过期也可能记错」）。一段说明挡不住任何人把推断当事实。
 *
 * 模型推断那一档故意不给链接：**没有可点的出处，本身就是信息**。
 */

type Kind = "年报" | "财报" | "公告" | "底座" | "模型推断";

const HINT: Record<Kind, string> = {
  年报: "来自年度报告原文，可回原文核对",
  // **「财报」跟「年报」不是一回事**：中报、季报也在里面。
  // 有些指标只有年报才披露（im-row 的 annual_only），那种要说年报；
  // 混着叫等于把一个季度的数说成一年的。
  财报: "来自定期报告（年报／中报／季报）",
  公告: "来自公司公告原文，可回原文核对",
  底座: "来自全市场同步的行情与财务底座",
  模型推断: "模型推断，**没有可核对的出处**——用它之前请自己查一眼",
};

export function Source({ kind, href, at }: {
  kind: Kind;
  /** 能点开的出处。**模型推断那一档不给链接**——没有出处本身就是信息。 */
  href?: string | null;
  /** 哪一期、哪一天。有就写上：「2025 年报」比「年报」有用得多。 */
  at?: string;
}) {
  const label = at ? `${kind}·${at}` : kind;
  const title = HINT[kind].replace(/\*\*/g, "");
  if (kind !== "模型推断" && href) {
    return <a className="src src--linked" href={href} target="_blank" rel="noreferrer" title={title}>
      <span aria-hidden="true">▸</span>{label}
    </a>;
  }
  return <span className={`src${kind === "模型推断" ? " src--guess" : ""}`} title={title}>
    <span aria-hidden="true">▸</span>{label}
  </span>;
}
